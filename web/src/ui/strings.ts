export type StringKey = keyof typeof EN;
export type StringValues = Record<string, string | number>;

export function s(key: StringKey, values?: StringValues): string {
  if (values === undefined) return EN[key];
  return EN[key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}
