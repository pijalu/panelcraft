// Mermaid interop matrix (F-21): the single place that states what the two
// converters understand. The document is *generated* from the converters'
// declared catalogues, and a test asserts the committed file matches — so a new
// capability or a new declared drop cannot land undocumented.

import { C4_DROP_CATALOGUE } from './mermaidC4';
import { EXPORT_DROP_CATALOGUE, UNRESOLVED_IMPORT_PREFIX } from './mermaidExport';

const IMPORT_ROWS = [
  ['flowchart / graph', 'yes', 'yes', 'shapes, subgraphs, chained/`&` edges'],
  ['sequenceDiagram', 'yes (→ flows)', 'no', 'participants → objects, messages → msg steps'],
  ['C4Context', 'yes', 'yes', 'Person/System/Container*/Component*, Rel*'],
  ['classDef + class', 'tags only (colours M100)', 'yes (from tags)', 'colours are declared drops'],
  ['linkStyle', 'yes (→ link style)', 'partial', 'stroke/dash mapped; width/index-only lost'],
  ['style', 'no (M200)', 'yes (fill only)', 'use classDef instead'],
  ['click', 'no (M200)', 'no', 'interaction has no PDL counterpart'],
] as const;

/** Render the matrix document from the converters' catalogues. */
export function mermaidMatrix(): string {
  const rows = IMPORT_ROWS.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} | ${r[3]} |`).join('\n');
  const exportDrops = EXPORT_DROP_CATALOGUE.map((d) => `- \`${d}\``).join('\n');
  const c4Drops = C4_DROP_CATALOGUE.map((d) => `- \`${d}\``).join('\n');
  return `# Mermaid interop matrix (generated)

<!-- Generated by web/src/engine/format/mermaidMatrix.ts — do not edit by hand.
     Regenerate with: MERMAID_MATRIX=1 npx vitest run web/src/engine/format/mermaidMatrix.test.ts -->

PanelCraft converts a documented subset of Mermaid in both directions and
**declares every loss** (SPEC FR-M4/M5): the exporter returns a dropped[] list
and the importer emits M200 diagnostics instead of ignoring lines silently.

## Import / export coverage

| Construct | Import (fromMermaid / fromC4) | Export (docToMermaid / docToC4) | Notes |
|---|---|---|---|
${rows}

## Declared export drops (\`docToMermaid\`)

Every string below can appear in \`dropped[]\`; anything starting with
\`${UNRESOLVED_IMPORT_PREFIX}\` reports an import that could not be inlined.

${exportDrops}

## Declared C4 export drops (\`docToC4\`)

${c4Drops}

## Importer diagnostics

| Code | Severity | Meaning |
|---|---|---|
| \`M100\` | info | recognised directive with no PDL counterpart (ignored) |
| \`M200\` | warning | unsupported construct skipped (never silent) |
`;
}
